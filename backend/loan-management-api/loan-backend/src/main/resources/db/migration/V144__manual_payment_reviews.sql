CREATE TABLE payment_reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL REFERENCES organizations(id),
    loan_id BIGINT NOT NULL REFERENCES loans(id),
    request_key VARCHAR(128) NOT NULL,
    amount NUMERIC(19,2) NOT NULL CHECK (amount > 0),
    method VARCHAR(32) NOT NULL,
    reference VARCHAR(100) NOT NULL,
    channel VARCHAR(50),
    notes VARCHAR(2000),
    submitted_by BIGINT NOT NULL,
    submitted_by_name VARCHAR(255) NOT NULL,
    submitted_at TIMESTAMP WITH TIME ZONE NOT NULL,
    status VARCHAR(16) NOT NULL CHECK (status IN ('PENDING','APPROVED','REJECTED')),
    decided_by BIGINT,
    decided_at TIMESTAMP WITH TIME ZONE,
    decision_reason VARCHAR(1000),
    CONSTRAINT uk_payment_review_request UNIQUE (organization_id, request_key),
    CHECK ((status = 'PENDING' AND decided_by IS NULL AND decided_at IS NULL)
        OR (status <> 'PENDING' AND decided_by IS NOT NULL AND decided_at IS NOT NULL AND decided_by <> submitted_by))
);

CREATE UNIQUE INDEX uk_payment_review_reference
    ON payment_reviews (organization_id, LOWER(reference)) WHERE status <> 'REJECTED';
CREATE INDEX idx_payment_review_queue
    ON payment_reviews (organization_id, status, submitted_at DESC);

